export default function ChannelFilter({ selected, counts, onChange }: Props) {
  const total = Object.values(counts).reduce((a, b) => a + b, 0);

  return (
    <div className="flex items-center gap-1.5 overflow-x-auto pb-1">
      {CHANNELS.map((ch) => {
        const isActive = selected === ch.key;
        const count = ch.key === "" ? total : (counts[ch.key] ?? 0);

        if (ch.key !== "" && count === 0) return null;

        return (
          <button
            key={ch.key}
            type="button"
            onClick={() => onChange(ch.key as LeadChannel | "")}
            className={`
              group flex items-center gap-1.5 rounded-full px-3 py-1.5
              text-xs font-medium whitespace-nowrap
              transition-all duration-200 ease-out
              ${isActive
                ? `${ch.bg} ${ch.color} shadow-sm ring-1 ring-black/5`
                : "text-slate-400 hover:text-slate-600 hover:bg-slate-50"
              }
            `}
          >
            <span className={`transition-colors duration-200 ${isActive ? ch.color : "text-slate-400 group-hover:text-slate-500"}`}>
              {ch.icon}
            </span>
            <span>{ch.label}</span>
            <span className={`
              ml-0.5 min-w-[18px] rounded-full px-1.5 py-0.5 text-center text-[10px] font-semibold tabular-nums leading-none
              transition-colors duration-200
              ${isActive
                ? `${ch.color} bg-white/60`
                : "text-slate-400 bg-slate-100 group-hover:bg-slate-200"
              }
            `}>
              {count}
            </span>
          </button>
        );
      })}
    </div>
  );
}
